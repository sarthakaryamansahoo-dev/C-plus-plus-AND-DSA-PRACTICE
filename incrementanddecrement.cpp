#include<iostream>
using namespace std;
int main()
{
    //increment and decrement
    //x++ - x=x+1  (that is called post increment and another example is x--)
    //++x - x=x+1  (that is called pre increment and another example is --x)
    int x=5;
    cout<<++x<<endl;
    cout<<x++<<endl;
    cout<<x;
}